from docx import Document
from openpyxl import Workbook


def generate_students_excel(filepath: str = "students.xlsx") -> None:
    wb = Workbook()

    # Группа 1: ИВТ-101
    ws1 = wb.active
    ws1.title = "ИВТ-101"
    ws1.append(["Фамилия", "Имя"])
    ws1.append(["Иванов", "Иван"])
    ws1.append(["Петров", "Пётр"])
    ws1.append(["Сидорова", "Анна"])
    ws1.append(["Кузнецов", "Дмитрий"])

    # Группа 2: ПИ-102
    ws2 = wb.create_sheet(title="ПИ-102")
    ws2.append(["Фамилия", "Имя"])
    ws2.append(["Смирнов", "Алексей"])
    ws2.append(["Морозова", "Елена"])
    ws2.append(["Волков", "Сергей"])

    # Группа 3: Пустая группа (для проверки требования "Пустая группа")
    ws3 = wb.create_sheet(title="БИ-103 (пустая)")
    ws3.append(["Фамилия", "Имя"])

    wb.save(filepath)
    wb.close()


